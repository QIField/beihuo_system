CREATE TABLE IF NOT EXISTS `wms_picking_list` (
 `pono` varchar(100) COLLATE utf8mb4_general_ci NOT NULL COMMENT '拣货单号',
  `type` int(11) DEFAULT NULL COMMENT '类型',
  `is_checkupdate` int(11) DEFAULT NULL COMMENT '是否检查更新',
  `orders_id` int(11) DEFAULT NULL COMMENT '订单ID',
  `orders_no` varchar(100) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '订单编号',
  `rid` varchar(100) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT 'RID',
  `frey_no` varchar(100) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT 'Frey单号',
  `status` int(11) DEFAULT NULL COMMENT '状态 0: 未开始, 1: 正在拣货, 2: 已完成',
  `partner_sapno` varchar(500) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '合作伙伴SAP编号',
  `fullname` varchar(500) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '全名',
  `orderdate` varchar(50) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '订单日期',
  `name` varchar(200) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '名称',
  `dhdate` varchar(50) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '到货日期',
  `jhdate` varchar(50) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '拣货日期',
  `qty` int(11) DEFAULT NULL COMMENT '数量',
  `toqty` int(11) DEFAULT NULL COMMENT '总数量',
  `l_name_zh` varchar(500) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '商品名称',
  `wait_pick_num` int(11) DEFAULT NULL COMMENT '待拣数量',
  `already_pick_num` int(11) DEFAULT NULL COMMENT '已拣数量',
  `supplier_short_name` varchar(255) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '供应商名称',
  `data_flag` int(11) DEFAULT '0' COMMENT '有问题的数据标志 0: 无, 1: 有  默认无',
  `store` varchar(100) COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '门店标识',
  `created_at` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '数据创建时间',
  `updated_at` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '数据更新时间',
  PRIMARY KEY (`pono`) USING BTREE,
  KEY `idx_orders_id` (`orders_id`) USING BTREE,
  KEY `idx_status` (`status`) USING BTREE,
  KEY `idx_orderdate` (`orderdate`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='WMS拣货单表';
