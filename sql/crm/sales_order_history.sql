-- 销售订单历史明细表
-- 表名: sales_order_history

CREATE TABLE IF NOT EXISTS sales_order_history (
    orders_items_id INT PRIMARY KEY COMMENT '订单明细ID',
    handler INT COMMENT '处理人ID',
    user_id INT COMMENT '用户ID（经收人）',
    seller_id INT COMMENT '销售员ID',
    customer_id INT COMMENT '客户ID',
    order_type_id INT COMMENT '订单类型ID',
    create_date INT COMMENT '创建时间戳',
    send_date INT COMMENT '发货时间戳',
    orders_id INT COMMENT '订单ID',
    ddno VARCHAR(255) COMMENT '订单号',
    ddsapno VARCHAR(255) COMMENT '订单金蝶号',
    status VARCHAR(50) COMMENT '订单状态（中文）',
    origin_status INT COMMENT '原始状态码',
    fullname VARCHAR(255) COMMENT '客户全称',
    quantity INT COMMENT '数量',
    sfqty INT COMMENT '实发数量',
    price DECIMAL(18, 4) COMMENT '单价',
    cost_price DECIMAL(18, 4) COMMENT '成本价',
    total_price DECIMAL(18, 4) COMMENT '总价',
    sfje DECIMAL(18, 4) COMMENT '实付金额',
    product_id INT COMMENT '产品ID',
    brand_id INT COMMENT '品牌ID',
    pdname VARCHAR(255) COMMENT '产品名称',
    frey_no VARCHAR(255) COMMENT '菲尔号',
    l_model_zh TEXT COMMENT '车型（中文）',
    number VARCHAR(255) COMMENT 'OE号',
    is_wms INT COMMENT '是否WMS订单',
    delivery_status INT COMMENT '发货状态',
    logistics_name VARCHAR(255) COMMENT '物流公司名称',
    kingdee_status INT COMMENT '金蝶状态',
    logistics_user_id INT COMMENT '物流用户ID',
    warehouse_no VARCHAR(255) COMMENT '仓库编号',
    brand_name VARCHAR(255) COMMENT '品牌名称',
    order_type_name VARCHAR(255) COMMENT '订单类型名称',
    user_name VARCHAR(255) COMMENT '用户名',
    creater VARCHAR(255) COMMENT '创建人',
    seller_name VARCHAR(255) COMMENT '销售员名称',
    deliverysapno VARCHAR(255) COMMENT '发货金蝶号',
    deliveryordersno VARCHAR(255) COMMENT '发货单号',
    store VARCHAR(255) COMMENT '门店标识',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '数据创建时间',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '数据更新时间',
    INDEX idx_orders_id (orders_id),
    INDEX idx_ddno (ddno),
    INDEX idx_customer_id (customer_id),
    INDEX idx_product_id (product_id),
    INDEX idx_create_date (create_date),
    INDEX idx_store (store),
    -- 复合索引：优化 find_matching_normal_orders 按 customer_id 匹配路径（order_type_id=1, number, customer_id, brand_name, pdname, frey_no, create_date）
    INDEX idx_normal_cid (`order_type_id`, `number`(60), `customer_id`, `brand_name`(50), `pdname`(80), `frey_no`(30), `create_date`),
    -- 复合索引：优化 find_matching_normal_orders 按 fullname 兜底匹配路径（order_type_id=1, number, fullname, brand_name, pdname, frey_no, create_date）
    INDEX idx_normal_name (`order_type_id`, `number`(60), `fullname`(50), `brand_name`(50), `pdname`(80), `frey_no`(30), `create_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='销售订单历史明细表';
