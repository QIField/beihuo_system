-- 订单状态类型表
-- 表名: wms_status_orders_type

CREATE TABLE IF NOT EXISTS wms_status_orders_type (
    id INT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    type VARCHAR(255) COMMENT '类型',
    is_checkupdate VARCHAR(255) COMMENT '是否检查更新',
    orders_id INT COMMENT '订单ID',
    orders_no VARCHAR(255) COMMENT '订单编号',
    pono VARCHAR(255) COMMENT '拣货单号',
    rid VARCHAR(255) COMMENT '关系ID',
    frey_no VARCHAR(255) COMMENT '货运单号',
    status VARCHAR(255) COMMENT '状态',
    partner_sapno VARCHAR(255) COMMENT '合作伙伴SAP编号',
    fullname VARCHAR(255) COMMENT '全名',
    orderdate VARCHAR(255) COMMENT '订单日期',
    name VARCHAR(255) COMMENT '名称',
    dhdate VARCHAR(255) COMMENT '到货日期',
    jhdate VARCHAR(255) COMMENT '计划日期',
    printtime VARCHAR(255) COMMENT '打印时间',
    companyname VARCHAR(255) COMMENT '公司名称',
    qty INT COMMENT '数量',
    toqty INT COMMENT '总数量',
    l_name_zh VARCHAR(255) COMMENT '中文名称',
    product_id VARCHAR(255) COMMENT '产品ID',
    order_source_type VARCHAR(255) COMMENT '订单来源类型',
    supplier_short_name VARCHAR(255) COMMENT '供应商简称',
    wait_pick_num INT COMMENT '待拣数量',
    already_pick_num INT COMMENT '已拣数量',
    delivery_status VARCHAR(255) COMMENT '发货状态',
    is_transfer_order VARCHAR(255) COMMENT '是否转运订单',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_orders_no (orders_no),
    UNIQUE INDEX idx_pono (pono),
    INDEX idx_orders_id (orders_id),
    INDEX idx_partner_sapno (partner_sapno),
    INDEX idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='订单状态类型表';
