CREATE TABLE IF NOT EXISTS `longsky_data` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `longsky_id` bigint NOT NULL COMMENT '长远内部ID',
  `crawl_batch` varchar(100) DEFAULT NULL COMMENT '批次号',
  `cp` varchar(100) DEFAULT NULL COMMENT '厂牌',
  `nno` varchar(100) DEFAULT NULL COMMENT '零件编码',
  `na1` varchar(255) DEFAULT NULL COMMENT '零件名称',
  `kcamount` decimal(10,2) DEFAULT NULL COMMENT '库存数',
  `oprc` decimal(10,2) DEFAULT NULL COMMENT '售价',
  `oprc2` decimal(10,2) DEFAULT NULL COMMENT '售价2',
  `oprc3` decimal(10,2) DEFAULT NULL COMMENT '售价3',
  `fa` varchar(255) DEFAULT NULL COMMENT '产地',
  `ty` varchar(100) DEFAULT NULL COMMENT '车型',
  `posi` varchar(100) DEFAULT NULL COMMENT '仓位',
  `depotno` varchar(100) DEFAULT NULL COMMENT '库号',
  `dc` varchar(100) DEFAULT NULL COMMENT '分类码', 
  `nno_clear` varchar(100) DEFAULT NULL COMMENT '零件编码清洗后的数据', 
  `dc_clear` varchar(100) DEFAULT NULL COMMENT '分类码清洗后的数据', 
  `unit` varchar(50) DEFAULT NULL COMMENT '单位',
  `nnp` varchar(100) DEFAULT NULL COMMENT '编码一',
  `nnq` varchar(100) DEFAULT NULL COMMENT '编码二',
  `note` varchar(255) DEFAULT NULL COMMENT '备注',
  `clean_status` tinyint NOT NULL DEFAULT '0' COMMENT '清洗状态：0未清洗 1清洗完成 2清洗失败 3无效数据（废弃） 4重复数据',
  `clean_error_msg` varchar(500) DEFAULT NULL COMMENT '清洗失败原因：报错日志、格式错误、缺失关键字段、解析异常等',
  `is_diff` tinyint NOT NULL DEFAULT '0' COMMENT '是否增量：1是 0否',
  `created_by` varchar(50) DEFAULT NULL COMMENT '创建人',
  `updated_by` varchar(50) DEFAULT NULL COMMENT '修改人',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`), 
  UNIQUE KEY `uk_longsky_id_crawl_batch` (`longsky_id`, `crawl_batch`), 
  KEY `idx_nno` (`nno`), 
  KEY `idx_cp` (`cp`), 
  KEY `idx_crawl_batch` (`crawl_batch`), 
  KEY `idx_clean_status` (`clean_status`), 
  KEY `idx_updated_at` (`updated_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='长远数据表';
